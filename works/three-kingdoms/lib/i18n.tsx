export function useLang() {
  const [lang, setLangState] = useState<Lang>(DEFAULT_LANG);
  useEffect(() => {
    try {
      const raw = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (raw === 'ar' || raw === 'zh' || raw === 'en') {
        setLangState(raw);
      }
    } catch {}
  }, []);
  useEffect(() => {
    try {
      document.documentElement.lang = pickHtmlLang(lang);
      document.documentElement.dir = pickDir(lang);
    } catch {}
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {}
    try {
      document.documentElement.lang = pickHtmlLang(l);
      document.documentElement.dir = pickDir(l);
    } catch {}
  }, []);
  const t = useCallback(
    (key: string) => STR[lang][key] ?? STR.zh[key] ?? STR.en[key] ?? key,
    [lang],
  );
  return { lang, setLang, t };
}

export function LangSwitcher({
  lang,
  setLang,
  t,
}: {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
}) {
  return (
    <div className="lang-switch" role="group" aria-label={t('lang.label')}>
      {(['ar', 'zh', 'en'] as Lang[]).map((l) => (
        <button
          key={l}
          className={lang === l ? 'active' : ''}
          aria-pressed={lang === l}
          onClick={() => setLang(l)}
        >
          {l === 'ar' ? 'العربية' : l === 'zh' ? '中文' : 'EN'}
        </button>
      ))}
    </div>
  );
}

/** Arabic display helpers. Original Chinese names are always kept alongside. */
export function cityName(id: string, fallback: string, lang: Lang): string {
  const key = `city.${id}`;
  const v = STR[lang][key];
  if (!v) return fallback;
  if (lang === 'ar') return `${fallback} · ${v}`;
  return v;
}
export function factionName(
  id: 'wei' | 'shu' | 'wu' | 'qun',
  lang: Lang,
): string {
  return STR[lang][`faction.${id}`] ?? STR.zh[`faction.${id}`] ?? id;
}
export function specialtyName(
  s: '统帅' | '勇将' | '谋士' | '内政',
  t: (k: string) => string,
): string {
  const m: Record<string, string> = {
    统帅: 'specialty.commander',
    勇将: 'specialty.brave',
    谋士: 'specialty.strategist',
    内政: 'specialty.civil',
  };
  return `${t(m[s])} · ${s}`;
}
