export function useLang() {
  const [lang, setLangState] = useState<Lang>(DEFAULT_LANG);
  useEffect(() => {
    try {
      const raw = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (raw === 'ar' || raw === 'zh' || raw === 'en') setLangState(raw);
    } catch {}
  }, []);
  useEffect(() => {
    try {
      document.documentElement.lang = pickHtmlLang(lang);
      document.documentElement.dir = pickDir(lang);
    } catch {}
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {}
    try {
      document.documentElement.lang = pickHtmlLang(l);
      document.documentElement.dir = pickDir(l);
    } catch {}
  }, []);
  const t = useCallback(
    (key: string) => STR[lang][key] ?? STR.zh[key] ?? STR.en[key] ?? key,
    [lang],
  );
  return { lang, setLang, t };
}

export function LangSwitcher({
  lang,
  setLang,
  t,
}: {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
}) {
  return (
    <div className="lang-switch" role="group" aria-label={t('lang.label')}>
      {(['ar', 'zh', 'en'] as Lang[]).map((l) => (
        <button
          key={l}
          className={lang === l ? 'active' : ''}
          aria-pressed={lang === l}
          onClick={() => setLang(l)}
        >
          {l === 'ar' ? 'العربية' : l === 'zh' ? '中文' : 'EN'}
        </button>
      ))}
    </div>
  );
}

/** Localized game meta without touching lib/game.ts logic. */
export function gameText(id: string, field: string, lang: Lang, fallback: string) {
  const map: Record<string, string> = {
    'lock:title': 'game.lock.title',
    'lock:desc': 'game.lock.desc',
    'lock:level': 'game.lock.level',
    'lock:objective': 'game.lock.obj',
    'lock:stage': 'game.lock.stage',
    'huarong-easy:title': 'game.easy.title',
    'huarong-easy:desc': 'game.easy.desc',
    'huarong-easy:level': 'game.easy.level',
    'huarong-easy:objective': 'game.easy.obj',
    'huarong-easy:stage': 'game.easy.stage',
    'huarong-classic:title': 'game.classic.title',
    'huarong-classic:desc': 'game.classic.desc',
    'huarong-classic:level': 'game.classic.level',
    'huarong-classic:objective': 'game.classic.obj',
    'huarong-classic:stage': 'game.classic.stage',
  };
  const key = map[`${id}:${field}`];
  if (!key) return fallback;
  return STR[lang][key] ?? fallback;
}

export function pieceName(id: string, lang: Lang, fallback: string) {
  const map: Record<string, string> = {
    cao: 'piece.cao',
    guan: 'piece.guan',
    zhang: 'piece.zhang',
    zhao: 'piece.zhao',
    ma: 'piece.ma',
    huang: 'piece.huang',
    bing1: 'piece.bing1',
    bing2: 'piece.bing2',
    bing3: 'piece.bing3',
    bing4: 'piece.bing4',
  };
  const key = map[id];
  if (!key) return fallback;
  const v = STR[lang][key] ?? fallback;
  if (lang === 'ar') return `${fallback} · ${v}`;
  return v;
}
